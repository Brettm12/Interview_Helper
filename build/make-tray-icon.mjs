// Emits src/main/trayIcon.ts — the menu-bar icon as a data URL.
// It has to be embedded rather than read off disk: the packaged asar ships
// only out/, package.json and zod (see electron-builder.yml), so build/ is not
// available at runtime. macOS template images are pure black + alpha; the OS
// recolours them for light/dark menu bars.
//   node build/make-tray-icon.mjs
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

const here = dirname(fileURLToPath(import.meta.url))

/** the app's mark reduced to something legible at 16px: a rounded panel
 *  outline with the listening dot and two point rows */
function svg(size) {
  const s = size
  const u = s / 22 // design on a 22pt grid, macOS menu-bar convention
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${s}" height="${s}" viewBox="0 0 ${s} ${s}">
    <rect x="${2 * u}" y="${3 * u}" width="${18 * u}" height="${16 * u}" rx="${4.5 * u}"
          fill="none" stroke="#000" stroke-width="${1.6 * u}"/>
    <circle cx="${6.6 * u}" cy="${8 * u}" r="${1.5 * u}" fill="#000"/>
    <rect x="${9.6 * u}" y="${7.2 * u}" width="${7 * u}" height="${1.6 * u}" rx="${0.8 * u}" fill="#000"/>
    <circle cx="${6.6 * u}" cy="${14 * u}" r="${1.5 * u}" fill="#000"/>
    <rect x="${9.6 * u}" y="${13.2 * u}" width="${5 * u}" height="${1.6 * u}" rx="${0.8 * u}" fill="#000"/>
  </svg>`
}

const png1x = await sharp(Buffer.from(svg(22))).png().toBuffer()
const png2x = await sharp(Buffer.from(svg(44))).png().toBuffer()

const out = `// GENERATED by build/make-tray-icon.mjs — do not edit by hand.
// Embedded because the packaged asar ships only out/ (see electron-builder.yml).
export const TRAY_ICON_1X = 'data:image/png;base64,${png1x.toString('base64')}'
export const TRAY_ICON_2X = 'data:image/png;base64,${png2x.toString('base64')}'
`
writeFileSync(join(here, '..', 'src', 'main', 'trayIcon.ts'), out)
console.log(`src/main/trayIcon.ts written (${png1x.length}B @1x, ${png2x.length}B @2x)`)
